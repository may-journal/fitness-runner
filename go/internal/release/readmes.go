// usageMarker brackets the command list in readmeFile.
const usageMarker = "fitness usage"

// docsChecksFile holds the check index, relative to the repository root.
const docsChecksFile = "docs/checks.md"

// readmeFile holds the command list, relative to the repository root.
const readmeFile = "README.md"

// checkIndex is the table of every check, linking its README, with the
// summary its doc comment opens with.
func checkIndex(docs []checkDoc) string {
	var b strings.Builder
	b.WriteString("| Check | Summary |\n| --- | --- |\n")
	for _, d := range docs {
		fmt.Fprintf(&b, "| [%s](../go/cmd/%s/README.md) | %s |\n", d.Name, d.Folder, strings.ReplaceAll(d.Summary, "|", `\|`))
	}
	return b.String()
}

// usageFile is the fitness command's source, whose usage constant is the
// command list `fitness --help` prints.
const usageFile = "go/cmd/fitness/main.go"

// usageBlock is the command list as the README shows it: the usage
// constant in a fenced block.
func (c Config) usageBlock() (string, error) {
	text, err := stringConst(filepath.Join(c.Root, filepath.FromSlash(usageFile)), "usage")
	if err != nil {
		return "", err
	}
	return "```text\n" + strings.TrimRight(text, "\n") + "\n```\n", nil
}

// stringConst is the value of the string constant name declares in the Go
// file at path.
func stringConst(file, name string) (string, error) {
	parsed, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
	if err != nil {
		return "", err
	}
	for _, decl := range parsed.Decls {
		if value := constValue(decl, name); value != "" {
			return strconv.Unquote(value)
		}
	}
	return "", fmt.Errorf("%s declares no string constant %s", file, name)
}

// constValue is the literal a const declaration gives name, or "".
func constValue(decl ast.Decl, name string) string {
	gen, ok := decl.(*ast.GenDecl)
	if !ok || gen.Tok != token.CONST {
		return ""
	}
	for _, spec := range gen.Specs {
		if value := specValue(spec.(*ast.ValueSpec), name); value != "" {
			return value
		}
	}
	return ""
}

// specValue is the string literal a value spec gives name, or "".
func specValue(value *ast.ValueSpec, name string) string {
	for i, ident := range value.Names {
		if lit, ok := literal(value, i); ok && ident.Name == name {
			return lit
		}
	}
	return ""
}

// literal is the string literal a value spec gives its i-th name, if any.
func literal(value *ast.ValueSpec, i int) (string, bool) {
	if i >= len(value.Values) {
		return "", false
	}
	lit, ok := value.Values[i].(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return "", false
	}
	return lit.Value, true
}

// withRegion returns the file at path, relative to the root, with the text
// between its opening and closing markers for name replaced by body, under
// a note naming source. A file missing either marker is an error, so the
// region cannot vanish unseen.
func (c Config) withRegion(rel, name, source, body string) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(c.Root, filepath.FromSlash(rel)))
	if err != nil {
		return nil, err
	}
	open, end := "<!-- begin "+name+" -->\n", "<!-- end "+name+" -->"
	before, rest, ok := strings.Cut(string(data), open)
	_, after, ok2 := strings.Cut(rest, end)
	if !ok || !ok2 {
		return nil, fmt.Errorf("%s: the %q and %q lines that hold the generated %s are missing", rel, strings.TrimSpace(open), end, name)
	}
	region := fmt.Sprintf(generatedNote, source) + "\n" + body + "\n"
	return []byte(before + open + region + end + after), nil
}
