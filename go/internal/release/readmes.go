package release

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// repoURL starts a link a doc comment writes to a file in this repository.
// A doc comment link needs a full URL, so `fitness explain` prints one; the
// generated READMEs turn it into a relative link, which markdown-links
// proves.
const repoURL = "https://github.com/may-journal/fitness-runner/blob/main/"

// generatedNote opens every Markdown file or region the generator writes,
// naming where to make a change instead.
const generatedNote = "<!-- Code generated by `fitness-release checks` from %s; DO NOT EDIT. -->\n"

// checkReadme is a check's README: a note naming its source, the check name
// as the title, and the body `fitness explain` prints, with its repository
// links made relative to the README's folder.
func checkReadme(d checkDoc) []byte {
	dir := "go/cmd/" + d.Folder
	note := fmt.Sprintf(generatedNote, "the doc comments of "+dir)
	return []byte(note + "\n# " + d.Name + "\n\n" + strings.TrimRight(relativeLinks(d.Body, dir), "\n") + "\n")
}

// relativeLinks rewrites each Markdown link to a file in this repository as
// a path relative to dir, a folder in it.
func relativeLinks(md, dir string) string {
	parts := strings.Split(md, "]("+repoURL)
	for i := 1; i < len(parts); i++ {
		parts[i] = relative(dir, parts[i])
	}
	return strings.Join(parts, "](")
}

// relative rewrites the repository path that opens rest, up to its anchor
// or the link's end, relative to dir.
func relative(dir, rest string) string {
	end := strings.IndexAny(rest, "#)")
	if end < 0 {
		return rest
	}
	rel, err := filepath.Rel(filepath.FromSlash(dir), filepath.FromSlash(rest[:end]))
	if err != nil {
		return rest
	}
	return filepath.ToSlash(rel) + rest[end:]
}

