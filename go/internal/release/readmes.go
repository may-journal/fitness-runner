// checkIndex is the table of every check, linking its README, with the
// summary its doc comment opens with.
func checkIndex(docs []checkDoc) string {
	var b strings.Builder
	b.WriteString("| Check | Summary |\n| --- | --- |\n")
	for _, d := range docs {
		fmt.Fprintf(&b, "| [%s](../go/cmd/%s/README.md) | %s |\n", d.Name, d.Folder, strings.ReplaceAll(d.Summary, "|", `\|`))
	}
	return b.String()
}

// usageBlock is the command list as the README shows it: the forms that
// run checks and the subcommands, each with its summary, as `fitness
// --help` prints them, in a fenced block.
func usageBlock(u usageDoc) string {
	var b strings.Builder
	b.WriteString("```text\nRun checks:\n")
	writeHelp(&b, u.Runner)
	b.WriteString("\nCommands:\n")
	writeHelp(&b, u.Commands)
	return b.String() + "```\n"
}

// writeHelp writes each entry's forms, then its summary indented below.
func writeHelp(b *strings.Builder, entries []usageEntry) {
	for _, e := range entries {
		for _, s := range e.Synopses {
			b.WriteString("  " + strings.TrimSpace("fitness "+s) + "\n")
		}
		b.WriteString("      " + e.Summary + "\n")
	}
}

// withRegion returns the file at path, relative to the root, with the text
// between its opening and closing markers for name replaced by body, under
// a note naming source. A file missing either marker is an error, so the
// region cannot vanish unseen.
func (c Config) withRegion(rel, name, source, body string) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(c.Root, filepath.FromSlash(rel)))
	if err != nil {
		return nil, err
	}
	open, end := "<!-- begin "+name+" -->\n", "<!-- end "+name+" -->"
	before, rest, ok := strings.Cut(string(data), open)
	_, after, ok2 := strings.Cut(rest, end)
	if !ok || !ok2 {
		return nil, fmt.Errorf("%s: the %q and %q lines that hold the generated %s are missing", rel, strings.TrimSpace(open), end, name)
	}
	region := fmt.Sprintf(generatedNote, source) + "\n" + body + "\n"
	return []byte(before + open + region + end + after), nil
}
