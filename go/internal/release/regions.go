package release

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// generatedNote opens every region the generator writes, naming where to
// make a change instead.
const generatedNote = "<!-- Code generated by `fitness-release checks` from %s; DO NOT EDIT. -->\n"

// usageMarker brackets the command list in readmeFile.
const usageMarker = "fitness usage"

// readmeFile holds the command list and the config keys, relative to the
// repository root.
const readmeFile = "README.md"

// region is one marked part of a Markdown file the generator writes.
type region struct {
	// name is the marker's name, as in `<!-- begin <name> -->`.
	name string
	// source names where the facts in the region come from.
	source string
	// body is the region's Markdown.
	body string
}

// usageBlock is the README command list in a fenced block, exactly as
// `fitness --help` prints it.
func usageBlock(u usageDoc) string {
	var b strings.Builder
	b.WriteString("```text\nRun checks:\n")
	writeHelp(&b, u.Runner)
	b.WriteString("\nCommands:\n")
	writeHelp(&b, u.Commands)
	return b.String() + "```\n"
}

// writeHelp writes each entry's forms, then its summary indented below.
func writeHelp(b *strings.Builder, entries []usageEntry) {
	for _, e := range entries {
		for _, s := range e.Synopses {
			b.WriteString("  " + strings.TrimSpace("fitness "+s) + "\n")
		}
		b.WriteString("      " + e.Summary + "\n")
	}
}

// entryList is a table of each entry's forms and summary, as the llms page
// shows them.
func entryList(entries []usageEntry) string {
	var b strings.Builder
	b.WriteString("| Form | Does |\n| --- | --- |\n")
	for _, e := range entries {
		forms := make([]string, len(e.Synopses))
		for i, s := range e.Synopses {
			forms[i] = "`" + strings.TrimSpace("fitness "+s) + "`"
		}
		fmt.Fprintf(&b, "| %s | %s |\n", cell(strings.Join(forms, " or ")), cell(e.Summary))
	}
	return b.String()
}

// keyList names each top-level config key on one line, as code spans.
func keyList(keys []string) string {
	spans := make([]string, len(keys))
	for i, key := range keys {
		spans[i] = "`" + key + "`"
	}
	return strings.Join(spans, ", ") + "\n"
}

// withRegions returns the file at rel with each region replaced, erroring on
// a missing marker so a region cannot vanish.
func (c Config) withRegions(rel string, regions []region) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(c.Root, filepath.FromSlash(rel)))
	text := string(data)
	for _, r := range regions {
		if err != nil {
			break
		}
		text, err = fill(rel, text, r)
	}
	return []byte(text), err
}

// fill replaces one region of text, the file at rel.
func fill(rel, text string, r region) (string, error) {
	open, end := "<!-- begin "+r.name+" -->\n", "<!-- end "+r.name+" -->"
	before, rest, ok := strings.Cut(text, open)
	_, after, ok2 := strings.Cut(rest, end)
	if !ok || !ok2 {
		return text, fmt.Errorf("%s: the %q and %q lines that hold the generated %s are missing", rel, strings.TrimSpace(open), end, r.name)
	}
	return before + open + fmt.Sprintf(generatedNote, r.source) + "\n" + r.body + "\n" + end + after, nil
}

// cell escapes the pipes in a table cell's text, which GitHub would read as
// column breaks even inside a code span.
func cell(text string) string {
	return strings.ReplaceAll(text, "|", "\\|")
}
