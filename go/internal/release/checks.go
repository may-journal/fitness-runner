package release

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// checksFile is the registry the fitness binary is built with, relative to
// the repository root.
const checksFile = "go/cmd/fitness/checks.go"

// WriteChecks rewrites go/cmd/fitness/checks.go from the check folders, so
// the fitness binary builds in every go/cmd/fitness-check-<name> package
// and no one keeps that list by hand. Each package exports Main.
func (c Config) WriteChecks() error {
	dirs, err := filepath.Glob(filepath.Join(c.Root, "go", "cmd", "fitness-check-*"))
	if err != nil {
		return err
	}
	var imports, entries strings.Builder
	for _, dir := range dirs {
		folder := filepath.Base(dir)
		name := strings.TrimPrefix(folder, "fitness-check-")
		alias := checkAlias(name)
		fmt.Fprintf(&imports, "\t%s \"github.com/may-journal/fitness-runner/go/cmd/%s\"\n", alias, folder)
		fmt.Fprintf(&entries, "\t%q: %s.Main,\n", name, alias)
	}
	source, err := format.Source([]byte(checksSource(imports.String(), entries.String())))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(c.Root, checksFile), source, 0o644)
}

// checksSource lays out the registry file around its import and map lines.
func checksSource(imports, entries string) string {
	return "// Code generated by `fitness-release checks`; DO NOT EDIT.\n\n" +
		"package main\n\n" +
		"import (\n" + imports + ")\n\n" +
		"// builtins maps each built-in check name to the entry point its package\n" +
		"// exports. The one fitness executable runs a check when started under the\n" +
		"// name fitness-check-<name>, or as `fitness check <name>`.\n" +
		"var builtins = map[string]func(){\n" + entries + "}\n"
}

// checkAlias names a check package's import: the check name in camel case,
// then Check, as go-test becomes goTestCheck. Empty words, as in a--b, add
// nothing.
func checkAlias(name string) string {
	words := strings.FieldsFunc(name, func(r rune) bool { return r == '-' })
	for i := 1; i < len(words); i++ {
		words[i] = strings.ToUpper(words[i][:1]) + words[i][1:]
	}
	return strings.Join(words, "") + "Check"
}
