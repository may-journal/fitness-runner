package release

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// checksFile is the registry the fitness binary is built with, relative to
// the repository root.
const checksFile = "go/cmd/fitness/checks.go"

// WriteChecks rewrites every file Generated returns, so the fitness binary
// builds in every go/cmd/fitness-check-<name> package with the docs its code
// comments hold, and no one keeps that list by hand.
func (c Config) WriteChecks() error {
	files, err := c.Generated()
	if err != nil {
		return err
	}
	for path, body := range files {
		if err := os.WriteFile(filepath.Join(c.Root, filepath.FromSlash(path)), body, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Stale lists each generated file, relative to the root, whose content
// differs from what WriteChecks would write, and how many files it writes.
// An error means the code holds something the generator cannot read, such
// as a check package without a doc comment.
func (c Config) Stale() (stale []string, total int, err error) {
	files, err := c.Generated()
	if err != nil {
		return nil, 0, err
	}
	for _, path := range slices.Sorted(maps.Keys(files)) {
		got, err := os.ReadFile(filepath.Join(c.Root, filepath.FromSlash(path)))
		if err != nil || !bytes.Equal(got, files[path]) {
			stale = append(stale, path)
		}
	}
	return stale, len(files), nil
}

// Generated returns each file the generator writes, by repository path, read
// from the check folders and their Go doc comments.
func (c Config) Generated() (map[string][]byte, error) {
	docs, err := c.checkDocs()
	if err != nil {
		return nil, err
	}
	registry, err := checksSource(docs)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{checksFile: registry}, nil
}

// checkDocs reads every go/cmd/fitness-check-<name> package, in name order.
func (c Config) checkDocs() ([]checkDoc, error) {
	dirs, err := filepath.Glob(filepath.Join(c.Root, "go", "cmd", "fitness-check-*"))
	if err != nil {
		return nil, err
	}
	docs := make([]checkDoc, 0, len(dirs))
	for _, dir := range dirs {
		d, err := readCheckDoc(dir)
		if err != nil {
			return nil, err
		}
		docs = append(docs, d)
	}
	return docs, nil
}

// checksSource lays out the registry file: each check package's import, its
// entry point, and its summary.
func checksSource(docs []checkDoc) ([]byte, error) {
	var imports, entries, summaries strings.Builder
	for _, d := range docs {
		alias := checkAlias(d.Name)
		fmt.Fprintf(&imports, "\t%s \"github.com/may-journal/fitness-runner/go/cmd/%s\"\n", alias, d.Folder)
		fmt.Fprintf(&entries, "\t%q: %s.Main,\n", d.Name, alias)
		fmt.Fprintf(&summaries, "\t%q: %q,\n", d.Name, d.Summary)
	}
	return format.Source([]byte("// Code generated by `fitness-release checks`; DO NOT EDIT.\n\n" +
		"package main\n\n" +
		"import (\n" + imports.String() + ")\n\n" +
		"// builtins maps each built-in check name to the entry point its package\n" +
		"// exports. The one fitness executable runs a check when started under the\n" +
		"// name fitness-check-<name>, or as `fitness check <name>`.\n" +
		"var builtins = map[string]func(){\n" + entries.String() + "}\n\n" +
		"// builtinSummaries maps each built-in check name to the first sentence\n" +
		"// of its package doc comment.\n" +
		"var builtinSummaries = map[string]string{\n" + summaries.String() + "}\n"))
}

// checkAlias names a check package's import: the check name in camel case,
// then Check, as go-test becomes goTestCheck. Empty words, as in a--b, add
// nothing.
func checkAlias(name string) string {
	words := strings.FieldsFunc(name, func(r rune) bool { return r == '-' })
	for i := 1; i < len(words); i++ {
		words[i] = strings.ToUpper(words[i][:1]) + words[i][1:]
	}
	return strings.Join(words, "") + "Check"
}
